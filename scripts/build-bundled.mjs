import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const file = name => new URL(name, root);
const source = readFileSync(file('douban-movie-exporter.user.js'), 'utf8');
const library = readFileSync(file('vendor/sheetjs-0.20.1/xlsx.full.min.js'));
const dependency = JSON.parse(readFileSync(file('vendor/sheetjs-0.20.1/SOURCE.json'), 'utf8'));
if (createHash('sha256').update(library).digest('hex') !== dependency.sha256) {
    throw new Error('Vendored SheetJS checksum does not match SOURCE.json');
}
const boundary = '// ==/UserScript==';
const end = source.indexOf(boundary);
if (end < 0) throw new Error('Missing userscript metadata boundary');
const header = source.slice(0, end);
const requirements = header.match(/^\/\/ @require\s+(.+)$/gm) || [];
if (requirements.length !== 1 || requirements[0].replace(/^\/\/ @require\s+/, '').trim() !== dependency.url) {
    throw new Error('Upstream dependencies changed; review the bundler before rebuilding');
}
const metadata = header.split('\n').filter(line => !line.startsWith('// @require')).map(line => {
    if (/^\/\/ @name(?::[^ ]+)?\s/.test(line)) return line + ' [Bundled]';
    if (line.startsWith('// @namespace')) return line + '/bundled';
    if (line.startsWith('// @license')) return '// @license      MIT AND Apache-2.0';
    return line;
}).join('\n');
const result = metadata + boundary + '\n\n// Generated by scripts/build-bundled.mjs. Edit the original userscript instead.\n// SheetJS 0.20.1: Apache-2.0, see vendor/sheetjs-0.20.1/LICENSE.\n' + library.toString('utf8') + '\n;\n// END BUNDLED DEPENDENCY\n' + source.slice(end + boundary.length);
const output = file('douban-movie-exporter.bundled.user.js');
if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== result) throw new Error('Bundled userscript is stale; run node scripts/build-bundled.mjs');
    console.log('Bundled userscript is up to date');
} else {
    writeFileSync(output, result);
    console.log('Built bundled userscript');
}
